<#
.SYNOPSIS
  Register the Next.js app (shift scheduler) as an always-on Windows Task Scheduler task. No extra software needed.

.DESCRIPTION
  Registers a task that starts at system boot and restarts the server 10 seconds after a crash.
  Run from a PowerShell opened as Administrator.

  Prerequisites:
    1. Node.js is installed on this server
    2. The web/ folder has been copied to its final location on this server
    3. npm install and npm run build have been run there (.next/standalone/ exists)
    4. .next/static and public/ have been copied into .next/standalone/ (Next.js standalone requirement)
         Copy-Item -Recurse .next\static .next\standalone\.next\static
         Copy-Item -Recurse public .next\standalone\public
    5. A data directory for the DB file, backups and logs has been decided
       (keep it separate from the code folder, e.g. C:\ShiftAppData\)

.PARAMETER DeployDir
  Folder containing server.js (the .next/standalone folder)

.PARAMETER DataDir
  Folder for dev.db, backups, logs and the generated start script

.PARAMETER Port
  Port Next.js listens on (default: 8002)

.PARAMETER SidecarUrl
  URL of the CP-SAT sidecar (default: http://127.0.0.1:8001)

.PARAMETER AdminPassword
  Shared login password (required). Every page except /dashboard needs it.
  The password must not contain a double quote character.

.EXAMPLE
  ./install-service.ps1 -DeployDir "C:\ShiftApp\web\.next\standalone" -DataDir "C:\ShiftAppData" -AdminPassword "your-password"
#>
param(
  [Parameter(Mandatory = $true)][string]$DeployDir,
  [Parameter(Mandatory = $true)][string]$DataDir,
  [Parameter(Mandatory = $true)][string]$AdminPassword,
  [int]$Port = 8002,
  [string]$SidecarUrl = "http://127.0.0.1:8001",
  [string]$TaskName = "ShiftWebApp"
)

$ErrorActionPreference = "Stop"

$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
  throw "Administrator rights required. Reopen PowerShell with Run as administrator."
}
if ($AdminPassword.Contains('"')) {
  throw "AdminPassword must not contain a double quote character."
}

$nodeExe = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $nodeExe) {
  throw "node.exe not found. Install Node.js first."
}

$serverJs = Join-Path $DeployDir "server.js"
if (-not (Test-Path $serverJs)) {
  throw "server.js not found: $serverJs (run npm run build and copy static/public into the standalone folder first)"
}

New-Item -ItemType Directory -Force -Path $DataDir | Out-Null
$dbPath = Join-Path $DataDir "dev.db"
if (-not (Test-Path $dbPath)) {
  Write-Warning "DB file not found at $dbPath. Run npx prisma migrate deploy first, or copy dev.db from the dev machine to this location."
}
$databaseUrl = "file:$($dbPath -replace '\\', '/')"

$logOut = Join-Path $DataDir "web-service.log"
$logErr = Join-Path $DataDir "web-service-error.log"
$runCmd = Join-Path $DataDir "run-shift-web.cmd"

# In cmd, % is special inside set statements, so double it
$pwEscaped = $AdminPassword -replace '%', '%%'

# Start script (contains the password, so only SYSTEM and Administrators may read it)
$cmdBody = @"
@echo off
rem Generated by install-service.ps1.
rem Task Scheduler does not restart a task after a crash exit, so this loop restarts the server.
set "NODE_ENV=production"
set "PORT=$Port"
set "HOSTNAME=0.0.0.0"
set "DATABASE_URL=$databaseUrl"
set "SIDECAR_URL=$SidecarUrl"
set "ADMIN_PASSWORD=$pwEscaped"
cd /d "$DeployDir"
:loop
for %%F in ("$logOut") do if exist "%%~F" if %%~zF gtr 10485760 move /y "%%~F" "%%~F.old" >nul
for %%F in ("$logErr") do if exist "%%~F" if %%~zF gtr 10485760 move /y "%%~F" "%%~F.old" >nul
"$nodeExe" "$serverJs" >> "$logOut" 2>> "$logErr"
echo [%date% %time%] server.js exited (code=%ERRORLEVEL%). Restarting in 10 seconds >> "$logErr"
ping -n 11 127.0.0.1 >nul
goto loop
"@
Set-Content -Path $runCmd -Value $cmdBody -Encoding Ascii
& icacls $runCmd /inheritance:r /grant:r "SYSTEM:F" "Administrators:F" | Out-Null

if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
  Write-Host "Replacing existing task '$TaskName'..."
  Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}
# Stopping the task leaves the child node.exe running, so stop this app's process explicitly
Get-CimInstance Win32_Process -Filter "Name='node.exe'" |
  Where-Object { $_.CommandLine -and $_.CommandLine.Contains($serverJs) } |
  ForEach-Object { Stop-Process -Id $_.ProcessId -Force }

Write-Host "Registering task '$TaskName'..."
$action = New-ScheduledTaskAction -Execute "cmd.exe" -Argument "/c `"$runCmd`""
$trigger = New-ScheduledTaskTrigger -AtStartup
$principal = New-ScheduledTaskPrincipal -UserId "SYSTEM" -LogonType ServiceAccount -RunLevel Highest
$settings = New-ScheduledTaskSettingsSet `
  -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
  -ExecutionTimeLimit (New-TimeSpan -Seconds 0) `
  -MultipleInstances IgnoreNew
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings `
  -Description "Shift scheduler (Next.js). Starts at boot, restarts 10 seconds after a crash." | Out-Null

Start-ScheduledTask -TaskName $TaskName

Write-Host ""
Write-Host "Done. Task name: $TaskName"
Write-Host "Check: http://<this-server-IP>:$Port"
Write-Host "Logs: $logOut / $logErr"
Write-Host ""
Write-Host "Do not forget to open inbound port $Port in Windows Firewall:"
Write-Host "  New-NetFirewallRule -DisplayName 'Shift Web App' -Direction Inbound -LocalPort $Port -Protocol TCP -Action Allow"
