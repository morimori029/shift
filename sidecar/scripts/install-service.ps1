<#
.SYNOPSIS
  Register the CP-SAT optimization sidecar (Python/FastAPI) as an always-on Windows Task Scheduler task. No extra software needed.

.DESCRIPTION
  Registers a task that starts at system boot and restarts the sidecar 10 seconds after a crash.
  Run from a PowerShell opened as Administrator.

  Prerequisites:
    1. Python 3.11 or later is installed on this server
    2. The sidecar/ folder has been copied to its final location on this server
    3. A virtual environment exists there and dependencies are installed:
         python -m venv .venv
         .venv\Scripts\pip install -r requirements.txt

.PARAMETER DeployDir
  Folder of sidecar/ (the one containing .venv)

.PARAMETER Port
  Port the sidecar listens on (default: 8001). It listens on 127.0.0.1 only and is never exposed to the LAN.

.EXAMPLE
  ./install-service.ps1 -DeployDir "C:\ShiftApp\sidecar"
#>
param(
  [Parameter(Mandatory = $true)][string]$DeployDir,
  [int]$Port = 8001,
  [string]$TaskName = "ShiftCpSatSidecar"
)

$ErrorActionPreference = "Stop"

$isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
  throw "Administrator rights required. Reopen PowerShell with Run as administrator."
}

$venvPython = Join-Path $DeployDir ".venv\Scripts\python.exe"
if (-not (Test-Path $venvPython)) {
  throw "venv python.exe not found: $venvPython (run python -m venv .venv and pip install -r requirements.txt first)"
}

$logDir = Join-Path $DeployDir "logs"
New-Item -ItemType Directory -Force -Path $logDir | Out-Null
$logOut = Join-Path $logDir "sidecar.log"
$logErr = Join-Path $logDir "sidecar-error.log"
$runCmd = Join-Path $DeployDir "run-sidecar.cmd"

$cmdBody = @"
@echo off
rem Generated by install-service.ps1.
rem Task Scheduler does not restart a task after a crash exit, so this loop restarts the sidecar.
cd /d "$DeployDir"
:loop
for %%F in ("$logOut") do if exist "%%~F" if %%~zF gtr 10485760 move /y "%%~F" "%%~F.old" >nul
for %%F in ("$logErr") do if exist "%%~F" if %%~zF gtr 10485760 move /y "%%~F" "%%~F.old" >nul
"$venvPython" -m uvicorn app.main:app --host 127.0.0.1 --port $Port >> "$logOut" 2>> "$logErr"
echo [%date% %time%] uvicorn exited (code=%ERRORLEVEL%). Restarting in 10 seconds >> "$logErr"
ping -n 11 127.0.0.1 >nul
goto loop
"@
Set-Content -Path $runCmd -Value $cmdBody -Encoding Ascii

if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
  Write-Host "Replacing existing task '$TaskName'..."
  Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}
# Stopping the task leaves the child python running, so stop this sidecar's process explicitly
Get-CimInstance Win32_Process |
  Where-Object { $_.CommandLine -and $_.CommandLine.Contains("uvicorn app.main:app --host 127.0.0.1 --port $Port") } |
  ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }

Write-Host "Registering task '$TaskName'..."
$action = New-ScheduledTaskAction -Execute "cmd.exe" -Argument "/c `"$runCmd`""
$trigger = New-ScheduledTaskTrigger -AtStartup
$principal = New-ScheduledTaskPrincipal -UserId "SYSTEM" -LogonType ServiceAccount -RunLevel Highest
$settings = New-ScheduledTaskSettingsSet `
  -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
  -ExecutionTimeLimit (New-TimeSpan -Seconds 0) `
  -MultipleInstances IgnoreNew
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings `
  -Description "CP-SAT optimization sidecar. Starts at boot, restarts 10 seconds after a crash." | Out-Null

Start-ScheduledTask -TaskName $TaskName

Write-Host ""
Write-Host "Done. Task name: $TaskName"
Write-Host "Check (on this server only, not exposed to the LAN): http://127.0.0.1:$Port/health"
Write-Host "Logs: $logOut / $logErr"
Write-Host ""
Write-Host "The sidecar listens on 127.0.0.1 only, so no firewall rule is needed (and never open one)."
